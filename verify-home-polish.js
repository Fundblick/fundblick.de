'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const js=fs.readFileSync('home-polish.js','utf8');
const css=fs.readFileSync('home-polish.css','utf8');
assert.ok(html.includes('id="searchFeedback"'),'dedicated homepage search feedback missing');
assert.ok(html.includes('home-polish.js?v=20260925-live19'),'homepage polish script must be cache-busted');
assert.ok(html.includes('home-polish.css?v=20260925-live19'),'homepage polish CSS must be cache-busted');
assert.ok(html.includes('data-home-build="20260925-live19"'),'homepage build marker missing');
assert.ok(!html.includes('id="showcaseList"'),'ordinary product cards must not appear on homepage without a search');
assert.ok(!html.includes('Product first. Offers second.'),'legacy product showcase heading must not return');
assert.ok(js.includes("event.stopImmediatePropagation()"),'empty submit must be intercepted before the legacy handler can duplicate feedback');
assert.ok(js.includes("voiceStatus.textContent=''"),'legacy empty-search message must be cleared');
assert.ok(js.includes("document.querySelectorAll('.showcase').forEach"),'legacy showcase must be defensively removed');
assert.ok(css.includes('.search input[aria-invalid="true"]{outline:none!important}'),'empty search must not draw the old red input outline');
assert.ok(css.includes('.search-feedback'),'green inline feedback styling missing');
assert.ok(css.includes('rgba(191,244,78,.56)'),'stronger green hero gradient missing');
assert.ok(css.includes('font-size:14px!important'),'desktop category controls should no longer look tiny');
console.log('homepage polish verification passed');

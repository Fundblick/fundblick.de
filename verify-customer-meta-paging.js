'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const index=fs.readFileSync('index.html','utf8');
const search=fs.readFileSync('search.html','utf8');
const meta=fs.readFileSync('page-meta-i18n.js','utf8');
const paging=fs.readFileSync('results-paging.js','utf8');
const pagingCss=fs.readFileSync('results-paging.css','utf8');
const workflow=fs.readFileSync('.github/workflows/production-pages.yml','utf8');
assert.ok(index.includes('page-meta-i18n.js?v=20260925-live25'),'homepage metadata localization must be loaded');
assert.ok(search.includes('page-meta-i18n.js?v=20260925-live25'),'results metadata localization must be loaded');
assert.ok(search.includes('results-paging.js?v=20260925-live25'),'results paging script must be loaded');
assert.ok(search.includes('results-paging.css?v=20260925-live25'),'results paging CSS must be loaded');
assert.ok(search.includes('<meta name="robots" content="noindex,follow">'),'search results must remain noindex,follow');
assert.ok(!/id="q"[^>]*\sautofocus(?:\s|>)/.test(index),'mobile homepage must not force keyboard focus');
assert.equal((meta.match(/homeTitle:/g)||[]).length,20,'metadata localization must cover all 20 supported languages');
assert.ok(meta.includes("document.documentElement.dir=(lang==='ar'||lang==='fa')?'rtl':'ltr'"),'RTL metadata helper must set page direction for Arabic and Persian');
assert.ok(meta.includes('document.title=isSearch&&query?'),'search browser title must include the active query');
assert.ok(paging.includes('const PAGE_SIZE=24'),'results must start with 24 visible cards');
assert.ok(paging.includes('visible+=PAGE_SIZE'),'load-more control must reveal the next result batch');
assert.ok(paging.includes('new MutationObserver'),'paging must reapply after filtering or sorting rerenders cards');
assert.ok(pagingCss.includes('.results-pager-button'),'load-more control styling missing');
const packageLine=workflow.split('\n').find(line=>line.trim().startsWith('cp index.html '))||'';
assert.ok(packageLine.includes('page-meta-i18n.js'),'localized metadata helper must ship to production');
assert.ok(packageLine.includes('results-paging.js')&&packageLine.includes('results-paging.css'),'paging assets must ship to production');
assert.ok(!packageLine.includes('adcell-feed-normalizer.js'),'ADCELL import normalizer must not be exposed in the public site artifact');
assert.ok(!packageLine.includes('site-i18n.js'),'unused site-i18n helper must not be exposed in the public site artifact');
assert.ok(!packageLine.includes('products.json'),'legacy DummyJSON product feed must not be exposed in production');
assert.ok(workflow.includes('test ! -e _site/products.json'),'production packaging must explicitly guard against legacy product-feed leakage');
console.log('customer metadata, paging and production exposure verification passed');

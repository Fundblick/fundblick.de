'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=process.argv[2]||path.join('build','anthbot-catalog');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
const products=[];
for(const shard of Object.values(manifest.shards||{}))products.push(...JSON.parse(fs.readFileSync(path.join(root,shard.file),'utf8')));
const anthbot=products.filter(p=>p?.source?.advertiserId==='125144');
assert.equal(anthbot.length,56,'isolated catalog must contain exactly 56 ANTHBOT physical products');
assert.equal(anthbot.filter(p=>p.inStock).length,34,'ANTHBOT in-stock count must remain 34 for the current verified feed snapshot');
assert.equal(anthbot.filter(p=>p.rawAttributes?.refurbished).length,4,'four refurbished products must remain labelled');
assert(anthbot.every(p=>p.testData===false),'ANTHBOT products must remain real data');
assert(anthbot.every(p=>p.brand==='ANTHBOT'),'bad feed brands must not escape normalization');
assert(anthbot.every(p=>p.bestOffer?.network==='awin'),'ANTHBOT offers must remain Awin offers');
assert(anthbot.every(p=>/awin1\.com/i.test(p.bestOffer?.affiliateUrl||'')),'every ANTHBOT offer needs its Awin affiliate URL');
assert(anthbot.every(p=>/^https:\/\/(?:[^/]+\.)?anthbot\.com\//i.test(p.bestOffer?.directUrl||'')),'every direct URL must remain on ANTHBOT');
assert(!anthbot.some(p=>/shipping protection|differenzgebühr|geschenkkarte|gift card|^4g service/i.test(p.name||'')),'non-product feed rows must not enter catalog');
assert(anthbot.some(p=>p.rawAttributes?.facets?.lawnAreaM2),'mower area facets must survive catalog build');
assert(anthbot.some(p=>p.rawAttributes?.facets?.connectivity4G===true),'4G facets must survive catalog build');
assert.equal(manifest.realCount>=56,true,'manifest must account for ANTHBOT as real products');
console.log(`ANTHBOT isolated catalog gate passed: ${anthbot.length} products, ${anthbot.filter(p=>p.inStock).length} in stock`);

'use strict';
const assert=require('node:assert/strict');
global.window={FundBlickLanguage:{lang:'de'}};
require('./facet-schemas.js');
const schemas=window.FB_CATEGORY_SCHEMAS;
assert.deepEqual(Object.keys(schemas).sort(),['coffee','headphones','heatgun','shoes','smartphone','tv']);
assert.equal(window.FB_detectCategory('Bluetooth Kopfhörer Over-Ear').key,'headphones');
assert.equal(window.FB_detectCategory('65 Zoll OLED Fernseher').key,'tv');
assert.equal(window.FB_detectCategory('Laufschuhe Größe 42').key,'shoes');
assert.equal(window.FB_detectCategory('Pixel Smartphone 256 GB').key,'smartphone');
assert.equal(window.FB_detectCategory('Heißluftfön 2000 W').key,'heatgun');
assert.equal(window.FB_detectCategory('Kaffeemaschine mit Timer').key,'coffee');
const cable=schemas.headphones.facets.find(x=>x.key==='cableLength');
const battery=schemas.headphones.facets.find(x=>x.key==='battery');
assert.equal(window.FB_facetVisible(cable,{connection:['Kabelgebunden']},''),true);
assert.equal(window.FB_facetVisible(cable,{connection:['Kabellos']},''),false);
assert.equal(window.FB_facetVisible(battery,{connection:['Kabelgebunden']},''),false);
assert.equal(window.FB_facetVisible(battery,{connection:['Kabellos']},''),true);
const search=require('./search.js');
const hp=search.normalize({active:true,name:'Test Over-Ear Bluetooth 5.3 headphones ANC 40 hours battery',brand:'Test',category:'audio',description:'foldable microphone',price:99});
assert.equal(hp.family,'headphones');
assert.equal(hp.attrs.connection,'Kabellos');
assert.equal(hp.attrs.form,'Over-Ear');
assert.equal(hp.attrs.bluetooth,'5.3');
assert.equal(hp.attrs.battery,40);
assert.ok(hp.attrs.features.includes('Active Noise Cancelling'));
const tv=search.normalize({active:true,name:'55 inch OLED 4K TV 120 Hz',brand:'Test',category:'electronics',description:'HDR HDMI 2.1 Gaming',price:799});
assert.equal(tv.family,'tv');
assert.equal(tv.attrs.screen,'55');
assert.equal(tv.attrs.panel,'OLED');
assert.equal(tv.attrs.resolution,'4K UHD');
assert.equal(tv.attrs.refresh,120);
console.log('live facet schema smoke tests passed');

'use strict';
const assert=require('node:assert/strict');
const offers=require('./merchant-offers.js');
const immun={merchant:'Ahipos Horses DE',name:'AHIPOS SULFO IMMUN – Sulforaphan und Spirulina Zusatzfutter',price:149.90};
const other={merchant:'Ahipos Horses DE',name:'AHIPOS anderes Produkt',price:49.90};
const foreign={merchant:'Anderer Händler',name:'AHIPOS SULFO IMMUN',price:149.90};
const before=Date.parse('2026-10-23T20:00:00+02:00');
const after=Date.parse('2026-10-24T00:00:01+02:00');
const hit=offers.forProduct(immun,before);
assert.equal(hit.length,1,'SULFO IMMUN must receive the verified voucher');
assert.equal(hit[0].code,'Immun10');
assert.equal(hit[0].discount.type,'percent');
assert.equal(hit[0].discount.value,10);
assert.equal(hit[0].conditions.minimumOrder,false);
assert.equal(hit[0].conditions.usagePerCustomer,1);
assert.equal(hit[0].conditions.combinable,false);
assert.equal(hit[0].conditions.newCustomersOnly,true);
assert.equal(offers.forProduct(other,before).length,0,'voucher must not leak to unrelated Ahipos products');
assert.equal(offers.forProduct(foreign,before).length,0,'voucher must not leak to another merchant');
assert.equal(offers.forProduct(immun,after).length,0,'expired voucher must disappear automatically');
assert.equal(hit[0].offerUrl,null,'partial/truncated Awin offer URL must never be invented');
const ru=offers.localized(hit[0],'ru');
assert.equal(ru.title,'Скидка 10 % на AHIPOS SULFO IMMUN','Russian voucher title must be explicitly localized');
assert.equal(ru.description,'Сульфорафан и спирулина (3 варианта)','Russian voucher description must be explicitly localized');
assert.equal(offers.publicOffer(hit[0],'ru').title,ru.title,'public offer must preserve requested localization');
console.log('Merchant offer voucher gate passed (DE + RU)');
